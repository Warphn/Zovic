-- Denúncias de comentários
-- =====================================================================

CREATE TABLE comment_reports (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    comment_id integer      NOT NULL,
    user_id    integer      NOT NULL,
    reason     varchar(280) NOT NULL,
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT comment_reports_pkey PRIMARY KEY (id),
    CONSTRAINT comment_reports_comment_id_fkey FOREIGN KEY (comment_id)
        REFERENCES comments (id) ON DELETE CASCADE,
    CONSTRAINT comment_reports_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE,
    CONSTRAINT comment_reports_comment_user_key UNIQUE (comment_id, user_id)
);
CREATE INDEX comment_reports_comment_id_idx ON comment_reports (comment_id);
CREATE INDEX comment_reports_user_id_idx ON comment_reports (user_id);

