-- =====================================================================
-- Zovic — convites do plano familiar
--
-- O gestor convida por email e entrega o link ao convidado (o sistema não
-- envia email). O link carrega um token aleatório; o banco guarda só o hash
-- SHA-256 dele (hex), então não há link utilizável guardado.
--
-- email: em minúsculas, como o da tabela "user", para comparar sem depender
--        da caixa.
-- Um convite está pendente enquanto accepted_at e canceled_at são nulos e
-- expires_at está no futuro. Cancelar o plano não escreve nos convites: a
-- consulta também exige plan.deleted_at nulo.
--
-- Também fixa o limite do plano Família em 4 pessoas (contando o gestor).
-- =====================================================================

CREATE TABLE plan_invitation (
    id          integer      GENERATED BY DEFAULT AS IDENTITY,
    plan_id     integer      NOT NULL,
    email       varchar(254) NOT NULL,
    token_hash  varchar(64)  NOT NULL,
    expires_at  timestamptz  NOT NULL,
    accepted_at timestamptz,
    canceled_at timestamptz,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT plan_invitation_pkey PRIMARY KEY (id),
    CONSTRAINT plan_invitation_token_hash_key UNIQUE (token_hash),
    CONSTRAINT plan_invitation_email_lower_check CHECK (email = lower(email)),
    CONSTRAINT plan_invitation_plan_id_fkey FOREIGN KEY (plan_id)
        REFERENCES plan (id) ON DELETE CASCADE
);
CREATE INDEX plan_invitation_plan_id_idx ON plan_invitation (plan_id);

UPDATE plan_type SET user_amount = 4 WHERE name = 'Família';
