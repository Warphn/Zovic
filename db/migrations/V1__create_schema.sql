CREATE INDEX music_user_user_id_idx ON music_user (user_id);

CREATE TABLE rating (
    id         integer     GENERATED BY DEFAULT AS IDENTITY,
    music_id   integer     NOT NULL,
    user_id    integer     NOT NULL,
    rating     smallint    NOT NULL,
    deleted_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT rating_pkey PRIMARY KEY (id),
    CONSTRAINT rating_music_id_fkey FOREIGN KEY (music_id)
        REFERENCES musics (id) ON DELETE CASCADE,
    CONSTRAINT rating_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE,
    CONSTRAINT rating_rating_check CHECK (rating BETWEEN 1 AND 5)
);
-- Uma avaliação ativa por usuário e música.
CREATE UNIQUE INDEX rating_music_id_user_id_key ON rating (music_id, user_id) WHERE deleted_at IS NULL;
CREATE INDEX rating_user_id_idx ON rating (user_id);

CREATE TABLE comments (
    id          integer     GENERATED BY DEFAULT AS IDENTITY,
    music_id    integer     NOT NULL,
    user_id     integer     NOT NULL,
    comment     text        NOT NULL,
    "timestamp" integer,    -- segundos desde o início da música
    deleted_at  timestamptz,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT comments_pkey PRIMARY KEY (id),
    CONSTRAINT comments_music_id_fkey FOREIGN KEY (music_id)
        REFERENCES musics (id) ON DELETE CASCADE,
    CONSTRAINT comments_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE,
    CONSTRAINT comments_timestamp_check CHECK ("timestamp" >= 0)
);
CREATE INDEX comments_music_id_idx ON comments (music_id);
CREATE INDEX comments_user_id_idx ON comments (user_id);

-- Relação 1:0..1 com musics (music_id único).
CREATE TABLE music_stats (
    id       integer          GENERATED BY DEFAULT AS IDENTITY,
    music_id integer          NOT NULL,
    genre    varchar(100),
    duration integer,
    streams  integer          NOT NULL DEFAULT 0,
