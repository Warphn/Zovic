-- Convenções (ver "Implementação física" em docs/modelo-er.md):
--   * Nomes de constraints/índices seguem o padrão do Prisma
--     (<tabela>_pkey, <tabela>_<coluna>_fkey, <tabela>_<colunas>_key/_idx),
--     para que o schema.prisma não precise de `map:`.
--   * Tabelas com deleted_at usam soft delete.
--   * updated_at é mantido pelo trigger set_updated_at().
--   * Tabelas associativas têm PK composta e ON DELETE CASCADE.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Funções utilitárias
-- ---------------------------------------------------------------------

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

