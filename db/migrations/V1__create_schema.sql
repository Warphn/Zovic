-- Valores provisórios: o modelo ER não lista os eventos.
-- Para acrescentar: ALTER TYPE user_event_type ADD VALUE '...';
CREATE TYPE user_event_type AS ENUM (
    'sign_up',
    'login',
    'logout',
    'music_play',
    'music_skip'
);

-- =====================================================================
-- Planos e usuários
-- =====================================================================

CREATE TABLE plan_type (
    id          integer       GENERATED BY DEFAULT AS IDENTITY,
    name        varchar(100)  NOT NULL,
    price       numeric(10,2) NOT NULL,
    user_amount integer       NOT NULL,
    deleted_at  timestamptz,
    updated_at  timestamptz   NOT NULL DEFAULT now(),
    created_at  timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT plan_type_pkey PRIMARY KEY (id),
    CONSTRAINT plan_type_price_check CHECK (price >= 0),
    CONSTRAINT plan_type_user_amount_check CHECK (user_amount > 0)
);

CREATE TABLE plan (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(100) NOT NULL,
    type_id    integer      NOT NULL,
    deleted_at timestamptz,
    updated_at timestamptz  NOT NULL DEFAULT now(),
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT plan_pkey PRIMARY KEY (id),
    CONSTRAINT plan_type_id_fkey FOREIGN KEY (type_id)
        REFERENCES plan_type (id) ON DELETE RESTRICT
);
CREATE INDEX plan_type_id_idx ON plan (type_id);

-- "user" é palavra reservada no Postgres: sempre entre aspas no SQL.
CREATE TABLE "user" (
    id         integer      GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(150) NOT NULL,
    birthdate  date,
    deleted_at timestamptz,
    updated_at timestamptz  NOT NULL DEFAULT now(),
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT user_pkey PRIMARY KEY (id)
);

CREATE TABLE plan_user (
    plan_id  integer NOT NULL,
    user_id  integer NOT NULL,
    is_admin boolean NOT NULL DEFAULT false,
    CONSTRAINT plan_user_pkey PRIMARY KEY (plan_id, user_id),
    CONSTRAINT plan_user_plan_id_fkey FOREIGN KEY (plan_id)
        REFERENCES plan (id) ON DELETE CASCADE,
    CONSTRAINT plan_user_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX plan_user_user_id_idx ON plan_user (user_id);

CREATE TABLE user_event (
    id         integer         GENERATED BY DEFAULT AS IDENTITY,
    user_id    integer         NOT NULL,
    event_type user_event_type NOT NULL,
    created_at timestamptz     NOT NULL DEFAULT now(),
    CONSTRAINT user_event_pkey PRIMARY KEY (id),
    CONSTRAINT user_event_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX user_event_user_id_created_at_idx ON user_event (user_id, created_at);

-- Linha única. O modelo ER não prevê id; a coluna `singleton` existe só para
-- (1) impedir uma segunda linha e (2) dar ao Prisma o identificador que ele exige.
CREATE TABLE system_data (
    singleton  boolean     NOT NULL DEFAULT true,
    users      integer     NOT NULL DEFAULT 0,
    songs      integer     NOT NULL DEFAULT 0,
    playlists  integer     NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT system_data_pkey PRIMARY KEY (singleton),
    CONSTRAINT system_data_singleton_check CHECK (singleton),
    CONSTRAINT system_data_counts_check CHECK (users >= 0 AND songs >= 0 AND playlists >= 0)
);

