-- =====================================================================
-- Triggers de updated_at
-- =====================================================================

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'plan_type', 'plan', 'user', 'system_data',
        'musics', 'lyrics', 'genre', 'album', 'artist',
        'rating', 'comments', 'playlists'
    ] LOOP
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE ON %I
             FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
            t || '_set_updated_at', t
        );
    END LOOP;
END;
$$;

