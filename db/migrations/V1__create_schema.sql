CREATE TABLE music_user (
    music_id   integer     NOT NULL,
    user_id    integer     NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    CONSTRAINT music_user_pkey PRIMARY KEY (music_id, user_id),
    CONSTRAINT music_user_music_id_fkey FOREIGN KEY (music_id)
        REFERENCES musics (id) ON DELETE CASCADE,
    CONSTRAINT music_user_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE
