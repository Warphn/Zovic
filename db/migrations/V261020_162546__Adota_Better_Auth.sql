-- =====================================================================
-- Zovic — tabelas do Better Auth (autenticação por email e senha)
-- Fonte: docs/superpowers/specs/2026-10-20-autenticacao-design.md
--
-- O Better Auth exige as tabelas user, session, account e verification. Aqui
-- elas seguem as mesmas convenções do V1 (constraints nomeadas no padrão do
-- Prisma, timestamptz, FKs com ON DELETE CASCADE) e os nomes em snake_case
-- são mapeados no código (api/adapters/auth/create-auth.ts).
-- Os ids são inteiros gerados pelo banco (advanced.database.generateId = "serial").
-- =====================================================================

-- ---------------------------------------------------------------------
-- "user": a tabela existente passa a ser a tabela de usuários do Better Auth
-- ---------------------------------------------------------------------

-- email é NULL para os usuários que já existiam: eles não têm credenciais e não
-- conseguem entrar até ganharem email e senha. UNIQUE aceita vários NULL no
-- Postgres, então não é preciso inventar um email falso. O Better Auth guarda
-- o email em minúsculas; o CHECK garante, e o UNIQUE comum já barra duplicados
-- que só diferem na caixa. O email de um usuário com soft delete continua
-- reservado (o UNIQUE vale para todas as linhas).
ALTER TABLE "user"
    ADD COLUMN email          varchar(254),
    ADD COLUMN email_verified boolean     NOT NULL DEFAULT false,
    ADD COLUMN image          text,
    -- Ao contrário das demais tabelas, "user" agora é atualizada (ex.: verificação de email).
    ADD COLUMN updated_at     timestamptz NOT NULL DEFAULT now(),
    ADD CONSTRAINT user_email_key UNIQUE (email),
    ADD CONSTRAINT user_email_lower_check CHECK (email = lower(email));

-- ---------------------------------------------------------------------
-- Sessões do cookie
-- ---------------------------------------------------------------------

CREATE TABLE session (
    id         integer     GENERATED BY DEFAULT AS IDENTITY,
    user_id    integer     NOT NULL,
    token      text        NOT NULL, -- valor do cookie de sessão
    expires_at timestamptz NOT NULL,
    ip_address text,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_pkey PRIMARY KEY (id),
    CONSTRAINT session_token_key UNIQUE (token),
    CONSTRAINT session_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX session_user_id_idx ON session (user_id);

-- ---------------------------------------------------------------------
-- Contas: uma por forma de login do usuário. A senha fica aqui (provider_id =
-- 'credential', já com hash); login social entra como outra linha, sem mudar
-- o schema.
-- ---------------------------------------------------------------------

CREATE TABLE account (
    id                       integer     GENERATED BY DEFAULT AS IDENTITY,
    user_id                  integer     NOT NULL,
    account_id               text        NOT NULL, -- id do usuário no provedor ('credential': o próprio id do usuário)
    provider_id              text        NOT NULL,
    password                 text,                 -- hash scrypt do Better Auth (só 'credential')
    access_token             text,
    refresh_token            text,
    id_token                 text,
    access_token_expires_at  timestamptz,
    refresh_token_expires_at timestamptz,
    scope                    text,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT account_pkey PRIMARY KEY (id),
    CONSTRAINT account_provider_id_account_id_key UNIQUE (provider_id, account_id),
    CONSTRAINT account_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX account_user_id_idx ON account (user_id);

-- ---------------------------------------------------------------------
-- Verificações: tokens de confirmação de email e de recuperação de senha
-- (ainda não usados; a tabela existe para o Better Auth e para a evolução).
-- ---------------------------------------------------------------------

CREATE TABLE verification (
    id         integer     GENERATED BY DEFAULT AS IDENTITY,
    identifier text        NOT NULL,
    value      text        NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT verification_pkey PRIMARY KEY (id)
);
CREATE INDEX verification_identifier_idx ON verification (identifier);
